// Run with PLAYWRIGHT_PATH pointing at an existing Playwright installation.
const { chromium } = require(process.env.PLAYWRIGHT_PATH || '/home/wwhvw/.codex/plugins/cache/personal-media-tools/local-library/0.3.0/node_modules/playwright');
const assert = require('node:assert/strict');
const path = require('node:path');
const fs = require('node:fs');
(async () => {
 const base=process.env.GALLERY_URL || 'http://172.17.0.2:8194';
 const browser=await chromium.launch({headless:true,executablePath:'/home/wwhvw/.cache/ms-playwright/chromium-1228/chrome-linux64/chrome',args:['--no-sandbox','--no-proxy-server','--autoplay-policy=no-user-gesture-required']});
 const page=await browser.newPage({viewport:{width:1440,height:1060}});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 const initial=await (await page.request.get(base+'/tts_gallery/catalog')).json();
 for(const row of initial.records.filter(r=>r.origin==='user' && ['Browser test voice','Edited browser voice'].includes(r.name_zh))) await page.request.delete(base+'/tts_gallery/voices/'+row.id,{data:{revision:row.revision}});
 await page.goto(base+'/tts_gallery/gallery'); await page.locator('.card').first().waitFor();
 assert.equal(await page.locator('.card').count(),36);
 await page.screenshot({path:path.join(__dirname,'../docs/gallery-zh.png'),fullPage:false});
 await page.locator('select[aria-label="模型"]').selectOption('drama3'); assert.equal(await page.locator('.card').count(),8);
 await page.locator('select[aria-label="控制类别"]').selectOption('scope'); assert.equal(await page.locator('.card').count(),1);
 await page.locator('.play').click(); await page.waitForFunction(()=>!document.getElementById('player').paused);
 await page.locator('.detail-link').click(); await page.locator('#detail').waitFor({state:'visible'});
 assert((await page.locator('#detail-body').innerText()).includes('<whisper>'));
 await page.locator('#detail .close').click();
 await page.locator('#voices').click(); assert.equal(await page.locator('.card').count(),1);
 await page.locator('.play').click(); await page.waitForFunction(()=>document.getElementById('player').src.includes('huola-dachu'));
 assert.equal(await page.locator('audio').count(),1);
 await page.locator('#en').click(); assert.equal(await page.locator('h1').innerText(),'Find the voice you have in mind.');
 await page.locator('#import').click();
 await page.locator('#audio-file').setInputFiles(path.join(__dirname,'../library/audio/huola-dachu.flac'));
 await page.locator('[name="name_zh"]').fill('Browser test voice');
 await page.locator('[name="reference_text"]').fill('大家好，我是火辣大厨。');
 await page.locator('[name="tags"]').fill('browser, warm');
 await page.locator('#save').click(); await page.locator('#editor').waitFor({state:'hidden'});
 await page.locator('#detail').waitFor({state:'visible'}); assert((await page.locator('#detail-body').innerText()).includes('Browser test voice'));
 await page.getByRole('button',{name:'Edit',exact:true}).click(); await page.locator('[name="name_zh"]').fill('Edited browser voice'); await page.locator('[name="reference_text"]').fill('修改后的逐字稿。');
 await page.locator('#save').click(); await page.locator('#editor').waitFor({state:'hidden'}); await page.waitForFunction(()=>document.querySelector('#detail h2')?.textContent==='Edited browser voice');
 page.once('dialog',d=>d.accept());await page.getByRole('button',{name:'Delete',exact:true}).click(); await page.locator('#detail').waitFor({state:'hidden'});
 assert.equal(await page.locator('.card').count(),1);
 await page.setViewportSize({width:390,height:844}); await page.locator('#zh').click(); await page.locator('.detail-link').click();
 await page.screenshot({path:path.join(__dirname,'../docs/detail-mobile.png'),fullPage:false});
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
 assert.deepEqual(errors,[]);
 console.log('Browser checks passed: filters, playback, details, language, import/edit/delete, mobile.');
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
