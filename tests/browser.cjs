// Run with PLAYWRIGHT_PATH pointing at an existing Playwright installation.
const { chromium } = require(process.env.PLAYWRIGHT_PATH || 'playwright');
const assert = require('node:assert/strict');
const path = require('node:path');
const fs = require('node:fs');
(async () => {
 const base=process.env.GALLERY_URL || 'http://127.0.0.1:8194';
 const browser=await chromium.launch({headless:true,executablePath:process.env.CHROMIUM_PATH || undefined,args:['--no-sandbox','--no-proxy-server','--autoplay-policy=no-user-gesture-required']});
 const page=await browser.newPage({viewport:{width:1440,height:1060}});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 const initial=await (await page.request.get(base+'/tts_gallery/catalog')).json();
 for(const row of initial.records.filter(r=>r.origin==='user' && ['Browser test voice','Edited browser voice'].includes(r.name_zh))) await page.request.delete(base+'/tts_gallery/voices/'+row.id,{data:{revision:row.revision}});
 await page.goto(base+'/tts_gallery/gallery'); await page.locator('.card').first().waitFor();
 assert.equal(await page.locator('.card').count(),initial.records.filter(r=>r.kind==='example').length);
 const expansion=await (await page.request.get(base+'/extensions/comfyui-tts-gallery/expansion.json')).json();
 if(expansion.status==='complete'){
  await page.locator('#expansion-status').waitFor({state:'hidden'});
  await page.route('**/extensions/comfyui-tts-gallery/expansion.json',route=>route.fulfill({json:{...expansion,status:'queued',completed:0}}));
  await page.reload();
 }
 await page.locator('#expansion-status').waitFor({state:'visible'});
 assert((await page.locator('#expansion-status').innerText()).includes('35'));
 await page.locator('#expansion-status summary').click();
 assert.equal(await page.locator('#expansion-status li').count(),35);
 const template=await (await page.request.get(base+'/extensions/comfyui-tts-gallery/templates/drama3_dialogue.json')).json();
 assert.equal(template.nodes.filter(n=>n.type==='TTSVoiceGallery').length,2);
 await page.locator('#expansion-status summary').click();
 await page.unroute('**/extensions/comfyui-tts-gallery/expansion.json');
 await page.reload(); await page.locator('.card').first().waitFor();
 await page.screenshot({path:path.join(__dirname,'../docs/gallery-zh.png'),fullPage:false});
 await page.locator('select[aria-label="模型"]').selectOption('drama3'); assert.equal(await page.locator('.card').count(),initial.records.filter(r=>r.model==='drama3').length);
 await page.locator('select[aria-label="控制类别"]').selectOption('whisper'); assert.equal(await page.locator('.card').count(),initial.records.filter(r=>r.model==='drama3' && r.category==='whisper').length);
 await page.locator('.card[data-id="drama3-chef-scoped"] .play').click(); await page.waitForFunction(()=>!document.getElementById('player').paused);
 await page.locator('.card[data-id="drama3-chef-scoped"] .detail-link').click(); await page.locator('#detail').waitFor({state:'visible'});
 assert((await page.locator('#detail-body').innerText()).includes('<whisper>'));
 await page.locator('#detail .close').click();
 await page.locator('#voices').click(); assert.equal(await page.locator('.card').count(),initial.records.filter(r=>r.kind==='voice').length);
 await page.locator('.card[data-id="huola-dachu"] .play').click(); await page.waitForFunction(()=>document.getElementById('player').src.includes('huola-dachu'));
 assert.equal(await page.locator('audio').count(),1);
 await page.locator('#en').click(); assert.equal(await page.locator('h1').innerText(),'Find the voice you have in mind.');
 await page.locator('#import').click();
 await page.locator('#audio-file').setInputFiles(path.join(__dirname,'../library/audio/huola-dachu.flac'));
 await page.locator('[name="name_zh"]').fill('Browser test voice');
 await page.locator('[name="reference_text"]').fill('大家好，我是火辣大厨。');
 await page.locator('[name="tags"]').fill('browser, warm');
 await page.locator('#save').click(); await page.locator('#editor').waitFor({state:'hidden'});
 await page.locator('#detail').waitFor({state:'visible'}); assert((await page.locator('#detail-body').innerText()).includes('Browser test voice'));
 await page.getByRole('button',{name:'Edit',exact:true}).click(); await page.locator('[name="name_zh"]').fill('Edited browser voice'); await page.locator('[name="reference_text"]').fill('修改后的逐字稿。');
 await page.locator('#save').click(); await page.locator('#editor').waitFor({state:'hidden'}); await page.waitForFunction(()=>document.querySelector('#detail h2')?.textContent==='Edited browser voice');
 page.once('dialog',d=>d.accept());await page.getByRole('button',{name:'Delete',exact:true}).click(); await page.locator('#detail').waitFor({state:'hidden'});
 assert.equal(await page.locator('.card').count(),initial.records.filter(r=>r.kind==='voice').length);
 await page.setViewportSize({width:390,height:844}); await page.locator('#zh').click(); await page.locator('.card[data-id="huola-dachu"] .detail-link').click();
 await page.screenshot({path:path.join(__dirname,'../docs/detail-mobile.png'),fullPage:false});
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
 assert.deepEqual(errors,[]);
 await page.route('**/tts_gallery/catalog',async route=>{const data=await (await route.fetch()).json(); data.records.push({...initial.records.find(r=>r.id==='drama3-chef-clone'),id:'fixture-dialogue',name_zh:'双人对话UI测试',mode:'dialogue',category:'dialogue',available:false,voice_ids:{voice0:'huola-dachu',voice1:'warm-female-zh'},text:'<|speaker:0|> 你好。\n<|speaker:1|> 你好。'}); await route.fulfill({json:data})});
 await page.goto(base+'/tts_gallery/gallery');
 await page.locator('.card[data-id="fixture-dialogue"] .detail-link').click();
 const detail=await page.locator('#detail-body').innerText();assert(detail.includes('<|speaker:0|> → 火辣大厨'));assert(detail.includes('<|speaker:1|> → 温暖女声'));
 assert.deepEqual(errors,[]);
 console.log('Browser checks passed: filters, playback, details, language, import/edit/delete, mobile.');
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
